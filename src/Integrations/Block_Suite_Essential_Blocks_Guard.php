/**
 * Refuses Essential Blocks writes that would render unstyled (issue #1009).
 *
 * The Essential Blocks editor generates each block's CSS from its controls
 * and saves it in the block's own blockMeta attribute (desktop, tab and
 * mobile CSS keyed by its blockId); StyleHandler builds the per-post
 * stylesheet only from that. The server cannot generate blockMeta, so:
 *  - a block inserted or imported must carry it (every Essential Blocks
 *    block in the subtree, except the few that generate no CSS);
 *  - an update that changes anything but text, labels and links must bring
 *    the matching blockMeta with it.
 * Edits of inner_html alone pass. A refusal is raised before any write or
 * snapshot, with code editor_render_required. Only while Essential Blocks
 * is active: an inactive suite's blocks are written as they are given.
 */
final class Block_Suite_Essential_Blocks_Guard
{
    // phpcs:disable WordPress.Security.EscapeOutput.ExceptionNotEscaped -- refusals are JSON tool errors surfaced by Integration_Dispatcher, never rendered as HTML.

    public const CODE = 'editor_render_required';

    private const NAMESPACE_PREFIX = 'essential-blocks/';

    /** Blocks whose editor generates no CSS (their attributes declare no blockMeta). */
    private const NO_GENERATED_CSS = [ 'essential-blocks/tab' ];

    /** The attribute holding the generated CSS. */
    private const META = 'blockMeta';

    /** Attribute names of text, labels and links, which change no generated CSS. */
    private const CONTENT_ONLY = '/^(?:text|title|content|label|caption|description|alt|url|link|href|[a-z][A-Za-z0-9]*(?:Text|Title|Content|Label|Caption|Description|Alt|Url|URL|Link|Href))$/';

    public function __construct(private readonly bool $active)
    {
    }

    /**
     * Refuse a block tree with an Essential Blocks block that has no blockMeta.
     *
     * @param array<mixed> $blocks parsed blocks
     * @throws Operation_Error
     */
    public function check_blocks(array $blocks): void
    {
        if (! $this->active) {
            return;
        }
        foreach ($blocks as $block) {
            if (! is_array($block)) {
                continue;
            }
            $name = is_string($block['blockName'] ?? null) ? $block['blockName'] : '';
            if ($this->generates_css($name) && ! $this->has_meta(is_array($block['attrs'] ?? null) ? $block['attrs'] : [])) {
                throw new Operation_Error(self::CODE, sprintf(
                    'Refusing to write %s without its blockMeta: its CSS is generated by the Essential Blocks editor, which the server cannot do. Copy the block as the Essential Blocks editor saved it (with blockMeta), or add it in the editor.',
                    $name
                ), [ 'block' => $name ]);
            }
            $this->check_blocks(is_array($block['innerBlocks'] ?? null) ? $block['innerBlocks'] : []);
        }
    }

    /**
     * Refuse an attribute patch on an Essential Blocks block that changes
     * more than text without bringing blockMeta.
     *
     * @param array<mixed> $patch attributes being set (null removes one)
     * @throws Operation_Error
     */
    public function check_update(string $block_name, array $patch): void
    {
        if (! $this->active || ! $this->generates_css($block_name) || $this->has_meta($patch)) {
            return;
        }
        $styled = [];
        foreach ($patch as $key => $value) {
            $key = is_string($key) ? $key : (string) $key;
            if (self::META === $key || 1 !== preg_match(self::CONTENT_ONLY, $key) || ! (is_string($value) || null === $value)) {
                $styled[] = $key;
            }
        }
        if ([] === $styled) {
            return;
        }
        throw new Operation_Error(self::CODE, sprintf(
            'Refusing to change %s of %s without blockMeta: its CSS is generated by the Essential Blocks editor, which the server cannot do. Send the blockMeta the Essential Blocks editor generates for the new values, change only its text, or edit it in the editor.',
            implode(', ', $styled),
            $block_name
        ), [ 'block' => $block_name, 'attributes' => $styled ]);
    }

    private function generates_css(string $block_name): bool
    {
        return 0 === strpos($block_name, self::NAMESPACE_PREFIX) && ! in_array($block_name, self::NO_GENERATED_CSS, true);
    }

    /** @param array<mixed> $attrs */
    private function has_meta(array $attrs): bool
    {
        $meta = $attrs[ self::META ] ?? null;
        return (is_array($meta) && [] !== array_filter($meta, static fn ($css): bool => is_string($css) && '' !== trim($css)))
            || (is_string($meta) && '' !== trim($meta));
    }

    // phpcs:enable WordPress.Security.EscapeOutput.ExceptionNotEscaped
}
