<?php

declare(strict_types=1);

namespace WPMCP\Registry;

use WPMCP\Api\V1\Value\Op;
use WPMCP\Api\V1\Version;
use WPMCP\Kernel\Flavor;

/**
 * One registry:build or registry:check run: scan, compile, validate, then
 * (build only, and only when valid) write the aggregates, the artifacts and
 * one surface.lock.php per module. Aggregates are flavor-filtered; locks
 * describe the full surface so they do not depend on the flavor built.
 */
final class Builder
{
    public const GENERATOR_VERSION = '1';

    private const LOCK_HEADER = 'GENERATED by composer registry:build. Do not edit: change the attributes and rebuild.';
    private const AGGREGATE_HEADER = 'GENERATED by composer registry:build (build/registry is never committed).';

    public function __construct(private readonly Build_Options $options)
    {
    }

    public function run(): Build_Result
    {
        $o = $this->options;
        $config = $o->config + self::config();
        $flavor = Flavors::get($o->flavor);
        if (null === $flavor) {
            return new Build_Result([sprintf('Unknown flavor %s (known: %s).', $o->flavor, implode(', ', array_keys(Flavors::all())))]);
        }

        $classes = (new Scanner($o->exclude))->scan($o->roots);
        $compiler = new Compiler($o->repo_root, $config);
        $model = $compiler->compile($classes);
        if ($o->auto && [] === $model['modules'] && [] === $compiler->errors()) {
            return new Build_Result([], ['No modules found; nothing to build.'], [], true);
        }

        $errors = array_merge($compiler->errors(), (new Validator($config, $o->repo_root))->validate($model, $o->addon));
        $abilities = $this->ordered_abilities($model);
        $shipped = $this->filter($model, $abilities, $flavor);
        $budget = $o->tools_list_budget ?? (int) ($config['tools_list_budget'] ?? 216000);
        $estimate = Validator::tools_list_bytes($shipped['abilities']);
        if ($estimate > $budget) {
            $errors[] = sprintf('tools/list estimate for flavor %s is %d bytes, over the %d byte budget.', $flavor->id, $estimate, $budget);
        }

        $locks = $this->locks($model, $abilities);
        if ($o->check) {
            foreach ($locks as $id => [$file, $code]) {
                if (! is_file($file) || (string) file_get_contents($file) !== $code) {
                    $errors[] = sprintf('surface.lock.php for module %s is stale or missing (%s); run composer registry:build and commit it.', $id, $compiler->relative($file));
                }
            }
            return new Build_Result($errors, $compiler->notes());
        }
        if ([] !== $errors) {
            return new Build_Result($errors, $compiler->notes());
        }

        $written = [];
        $files = $this->aggregates($model, $shipped, $flavor);
        $tmp = $o->out . '.tmp-' . getmypid();
        self::remove($tmp);
        foreach ($files as $name => $data) {
            self::write($tmp . '/' . $name, Php_Exporter::file($data, self::AGGREGATE_HEADER));
        }
        self::remove($o->out);
        self::ensure_dir(dirname($o->out));
        rename($tmp, $o->out);
        foreach (array_keys($files) as $name) {
            $written[] = $o->out . '/' . $name;
        }
        if (null !== $o->artifacts) {
            foreach ($this->artifacts($model, $shipped, $flavor) as $name => $content) {
                self::write($o->artifacts . '/' . $name, $content);
                $written[] = $o->artifacts . '/' . $name;
            }
        }
        if ($o->locks) {
            foreach ($locks as [$file, $code]) {
                if (! is_file($file) || (string) file_get_contents($file) !== $code) {
                    self::write($file, $code);
                }
                $written[] = $file;
            }
        }

        $notes = $compiler->notes();
        $notes[] = sprintf('flavor %s: %d modules, %d abilities, tools/list estimate %d bytes', $flavor->id, count($shipped['modules']), count($shipped['abilities']), $estimate);
        return new Build_Result([], $notes, $written);
    }

    /** @return array<string, mixed> */
    public static function config(): array
    {
        $config = require dirname(__DIR__) . '/config.php';
        return is_array($config) ? $config : [];
    }

    /**
     * Module order, then position, then name for abilities without one (D5).
     *
     * @param array<string, mixed> $model
     * @return list<array<string, mixed>>
     */
    private function ordered_abilities(array $model): array
    {
        $order = [];
        foreach ($model['modules'] as $id => $module) {
            $order[ $id ] = [(int) $module['order'], $id];
        }
        $abilities = array_values(array_filter($model['abilities'], static fn (array $a): bool => isset($order[ $a['module'] ])));
        foreach ($abilities as $i => $a) {
            $abilities[ $i ]['tier'] ??= $model['modules'][ $a['module'] ]['tier'];
        }
        usort($abilities, static function (array $a, array $b) use ($order): int {
            return [$order[ $a['module'] ], null === $a['position'] ? 1 : 0, $a['position'] ?? 0, $a['name']]
                <=> [$order[ $b['module'] ], null === $b['position'] ? 1 : 0, $b['position'] ?? 0, $b['name']];
        });
        return $abilities;
    }

    /**
     * @param array<string, mixed>        $model
     * @param list<array<string, mixed>> $abilities
     * @return array{modules: array<string, array<string, mixed>>, abilities: list<array<string, mixed>>, contributors: list<array<string, mixed>>}
     */
    private function filter(array $model, array $abilities, Flavor $flavor): array
    {
        $modules = $model['modules'];
        uasort($modules, static fn (array $a, array $b): int => [$a['order'], $a['id']] <=> [$b['order'], $b['id']]);
        $modules = array_filter($modules, static fn (array $m): bool => $flavor->includes_module($m));
        $shipped = [];
        foreach ($abilities as $a) {
            if (isset($modules[ $a['module'] ]) && $flavor->includes_ability($a)) {
                $a['tier'] = $flavor->tier_for((string) $a['name'], (string) $a['tier']);
                $shipped[] = $a;
            }
        }
        $contributors = array_values(array_filter($model['contributors'], static fn (array $c): bool => isset($modules[ $c['module'] ])));
        usort($contributors, static fn (array $a, array $b): int => [$a['dispatcher'], $a['order'], $a['seq']] <=> [$b['dispatcher'], $b['order'], $b['seq']]);
        return ['modules' => $modules, 'abilities' => $shipped, 'contributors' => $contributors];
    }

    /**
     * @param array<string, mixed> $model
     * @param array{modules: array<string, array<string, mixed>>, abilities: list<array<string, mixed>>, contributors: list<array<string, mixed>>} $shipped
     * @return array<string, mixed> file name => data
     */
    private function aggregates(array $model, array $shipped, Flavor $flavor): array
    {
        $modules = $shipped['modules'];
        $in = static fn (array $row): bool => isset($modules[ $row['module'] ]);
        $strip = static function (array $row, array $keys): array {
            foreach ($keys as $key) {
                unset($row[ $key ]);
            }
            return $row;
        };

        $hooks = array_values(array_filter($model['hooks'], $in));
        usort($hooks, static fn (array $a, array $b): int => [$modules[ $a['module'] ]['order'], $a['seq']] <=> [$modules[ $b['module'] ]['order'], $b['seq']]);
        $hooks = array_map(static fn (array $h): array => $strip($h, ['seq']), $hooks);

        $gates = [];
        foreach ($model['gate_rows'] as $g) {
            if ($in($g)) {
                $gates[ $g['filter'] ] = $strip($g, ['filter']);
            }
        }
        $providers = [];
        $bindings = [];
        foreach ($model['providers'] as $interface => $rows) {
            $rows = array_values(array_filter($rows, $in));
            usort($rows, static fn (array $a, array $b): int => [$a['priority'], $a['class']] <=> [$b['priority'], $b['class']]);
            if ([] !== $rows) {
                $providers[ $interface ] = $rows;
                $bindings[ $interface ] = $rows[0]['class'];
            }
        }
        $families = [];
        foreach ($model['families'] as $family => $rows) {
            $rows = array_values(array_filter($rows, $in));
            usort($rows, static fn (array $a, array $b): int => [$a['order'], $a['key']] <=> [$b['order'], $b['key']]);
            $families[ $family ] = $rows;
        }
        ksort($families);
        $factories = $model['factories'];
        ksort($factories);
        ksort($providers);
        ksort($bindings);
        ksort($gates);

        $ownership = ['namespaces' => [], 'paths' => []];
        foreach ($modules as $id => $m) {
            $ownership['namespaces'][ $m['namespace'] ] = $id;
            foreach ($m['owns'] as $glob) {
                $ownership['paths'][ $glob ] = $id;
            }
        }

        $boot_modules = [];
        $data = [];
        $refusals = [];
        foreach ($modules as $id => $m) {
            $boot_modules[ $id ] = $strip($m, ['data']);
            if (null !== $m['data']) {
                $data[ $id ] = $m['data'];
            }
            $this->refusal($refusals, $m['requires']);
        }
        foreach ($shipped['contributors'] as $c) {
            $this->refusal($refusals, $c['requires']);
        }
        ksort($refusals);

        $files = [
            'boot.php' => [
                'format' => Version::REGISTRY_FORMAT,
                'hash' => $this->hash($model),
                'flavor' => $flavor->id,
                'flavor_definition' => $flavor->to_array(),
                'modules' => $boot_modules,
                'hooks' => $hooks,
                'opt_in_gates' => $gates,
                'admin_pages' => array_values(array_filter($model['admin_pages'], $in)),
                'ajax' => array_values(array_filter($model['ajax'], $in)),
                'admin_post' => array_values(array_filter($model['admin_post'], $in)),
                'factories' => $factories,
                'bindings' => $bindings,
                'providers' => $providers,
                'dispatchers' => array_filter($model['dispatchers'], $in),
                'snapshot_types' => array_filter($model['snapshot_types'], $in),
                'table_kinds' => array_filter($model['table_kinds'], $in),
                'families' => $families,
                'direct_writes' => array_values(array_filter($model['direct_writes'], $in)),
                'ownership' => $ownership,
            ],
            'abilities.php' => array_map(static fn (array $a): array => $strip($a, ['position', 'seq', 'exclude_flavors']), $shipped['abilities']),
            'data.php' => $data,
            'refusal-plugins.php' => $refusals,
            'skills.php' => $this->skills($model, $modules),
        ];
        $by_dispatcher = [];
        foreach ($shipped['contributors'] as $c) {
            $by_dispatcher[ $c['dispatcher'] ][] = $strip($c, ['seq']);
        }
        foreach ($by_dispatcher as $slug => $rows) {
            $files[ 'ops/' . $slug . '.php' ] = $rows;
        }
        return $files;
    }

    /**
     * @param array<string, array<string, mixed>> $refusals
     * @param array<string, mixed>|null           $requires
     */
    private function refusal(array &$refusals, ?array $requires): void
    {
        if (null === $requires || ! isset($requires['name']) || isset($refusals[ $requires['name'] ])) {
            return;
        }
        $refusals[ (string) $requires['name'] ] = [
            'plugin' => $requires['plugin'] ?? [],
            'slug' => $requires['slug'] ?? null,
            'url' => $requires['url'] ?? null,
            'several' => (bool) ($requires['several'] ?? false),
        ];
    }

    /**
     * @param array<string, mixed>                  $model
     * @param array<string, array<string, mixed>>   $modules
     * @return array<string, array<string, mixed>>
     */
    private function skills(array $model, array $modules): array
    {
        $out = [];
        foreach ((array) ($model['skills'] ?? []) as $slug => $rows) {
            foreach ($rows as $row) {
                if (isset($modules[ $row['module'] ]) && ! isset($out[ $slug ])) {
                    $out[ (string) $slug ] = $row;
                }
            }
        }
        ksort($out);
        return $out;
    }

    /** @param array<string, mixed> $model */
    private function hash(array $model): string
    {
        $files = $model['files'];
        ksort($files);
        return sha1(self::GENERATOR_VERSION . '|' . Version::REGISTRY_FORMAT . '|' . json_encode($files));
    }

    /**
     * @param array<string, mixed>        $model
     * @param list<array<string, mixed>> $abilities full, ordered
     * @return array<string, array{string, string}> module id => [lock file, code]
     */
    private function locks(array $model, array $abilities): array
    {
        $out = [];
        foreach ($model['modules'] as $id => $m) {
            $mine = array_values(array_filter($abilities, static fn (array $a): bool => $a['module'] === $id));
            $ops = [];
            foreach ($model['contributors'] as $c) {
                if ($c['module'] === $id) {
                    foreach (array_keys($c['ops']) as $op) {
                        $ops[ $c['dispatcher'] ][] = (string) $op;
                    }
                }
            }
            ksort($ops);
            $gates = [];
            foreach ($model['gate_rows'] as $g) {
                if ($g['module'] === $id) {
                    $gates[] = $g['filter'];
                }
            }
            $hooks = [];
            foreach ($model['hooks'] as $h) {
                if ($h['module'] === $id) {
                    $hooks[] = sprintf('%s %s %s::%s %d', $h['kind'], $h['hook'], $h['class'], $h['method'], $h['priority']);
                }
            }
            $lock = [
                'module' => $id,
                'group' => $m['group'],
                'order' => $m['order'],
                'tier' => $m['tier'],
                'flavors' => $m['flavors'],
                'exclude_flavors' => $m['exclude_flavors'],
                'abilities' => array_map(static function (array $a): array {
                    $hints = Op::from((string) $a['operation'])->hints();
                    return [
                        'name' => $a['name'],
                        'tier' => $a['tier'],
                        'operation' => $a['operation'],
                        'hints' => [$a['read_only'] ?? $hints[0], $a['destructive'] ?? $hints[1], $a['idempotent'] ?? $hints[2]],
                        'capability' => $a['capability'],
                        'domain' => $a['domain'],
                        'input_hash' => sha1((string) json_encode($a['input'])),
                        'output_hash' => null === $a['output'] ? null : sha1((string) json_encode($a['output'])),
                        'description_bytes' => strlen((string) $a['description']),
                        'exposure' => $a['exposure'],
                        'exclude_flavors' => $a['exclude_flavors'],
                    ];
                }, $mine),
                'operations' => $ops,
                'opt_in_gates' => $gates,
                'hooks' => $hooks,
                'tools_list_bytes' => Validator::tools_list_bytes($mine),
            ];
            $dir = null !== $this->options->locks_root
                ? rtrim($this->options->locks_root, '/') . '/' . $id
                : (str_starts_with((string) $m['dir'], '/') ? (string) $m['dir'] : rtrim($this->options->repo_root, '/') . '/' . $m['dir']);
            $out[ is_string($id) ? $id : (string) json_encode($id) ] = [$dir . '/surface.lock.php', Php_Exporter::file($lock, self::LOCK_HEADER, true)];
        }
        return $out;
    }

    /**
     * @param array<string, mixed> $model
     * @param array{modules: array<string, array<string, mixed>>, abilities: list<array<string, mixed>>, contributors: list<array<string, mixed>>} $shipped
     * @return array<string, string>
     */
    private function artifacts(array $model, array $shipped, Flavor $flavor): array
    {
        $counts_file = (string) $this->options->artifacts . '/counts.json';
        $counts = is_file($counts_file) ? (array) json_decode((string) file_get_contents($counts_file), true) : [];
        $tiers = array_count_values(array_map(static fn (array $a): string => (string) $a['tier'], $shipped['abilities']));
        $op_count = 0;
        foreach ($shipped['contributors'] as $c) {
            $op_count += count($c['ops']);
        }
        $counts[ $flavor->id ] = [
            'total' => count($shipped['abilities']),
            'free' => $tiers['free'] ?? 0,
            'pro' => $tiers['pro'] ?? 0,
            'modules' => count($shipped['modules']),
            'operations' => $op_count,
        ];
        ksort($counts);

        $manifest = [];
        foreach ($shipped['abilities'] as $a) {
            $manifest[ $a['name'] ] = $a['tier'];
        }
        $plugins = [];
        foreach ($shipped['modules'] as $m) {
            foreach ($m['test_plugins'] as $p) {
                $plugins[ $p ] = true;
            }
        }
        $plugins = array_keys($plugins);
        sort($plugins);
        $catalog = [
            'flavor' => $flavor->id,
            'abilities' => array_map(static fn (array $a): array => [
                'name' => $a['name'], 'module' => $a['module'], 'group' => $shipped['modules'][ $a['module'] ]['group'],
                'tier' => $a['tier'], 'description' => $a['description'], 'domain' => $a['domain'], 'operation' => $a['operation'],
            ], $shipped['abilities']),
            'operations' => [],
            'features' => [],
        ];
        foreach ($shipped['contributors'] as $c) {
            foreach ($c['ops'] as $op => $meta) {
                $catalog['operations'][ $c['dispatcher'] ][] = ['op' => $op, 'mode' => $meta['mode'], 'module' => $c['module'], 'host' => $c['hosts'][ $op ] ?? $c['host']];
            }
        }
        foreach ($shipped['modules'] as $id => $m) {
            if ([] !== $m['features']) {
                $catalog['features'][ $id ] = $m['features'];
            }
        }
        $json = JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE;
        $out = [
            'counts.json' => json_encode($counts, $json) . "\n",
            'catalog-' . $flavor->id . '.json' => json_encode($catalog, $json) . "\n",
            'ability-manifest-' . $flavor->id . '.php' => Php_Exporter::file($manifest, self::AGGREGATE_HEADER),
            'test-plugins-' . $flavor->id . '.txt' => [] === $plugins ? '' : implode("\n", $plugins) . "\n",
        ];
        if ('full' === $flavor->id) {
            // The canonical names other tools read (the tools reference generator, install-test-plugins).
            $out['catalog.json'] = $out['catalog-full.json'];
            $out['ability-manifest.php'] = $out['ability-manifest-full.php'];
            $out['test-plugins.txt'] = $out['test-plugins-full.txt'];
        }
        return $out;
    }

    private static function write(string $file, string $content): void
    {
        self::ensure_dir(dirname($file));
        $tmp = $file . '.tmp-' . getmypid();
        file_put_contents($tmp, $content);
        rename($tmp, $file);
    }

    private static function ensure_dir(string $dir): void
    {
        if (! is_dir($dir)) {
            mkdir($dir, 0777, true);
        }
    }

    private static function remove(string $path): void
    {
        if (is_dir($path) && ! is_link($path)) {
            foreach (scandir($path) ?: [] as $entry) {
                if ('.' !== $entry && '..' !== $entry) {
                    self::remove($path . '/' . $entry);
                }
            }
            rmdir($path);
        } elseif (file_exists($path) || is_link($path)) {
            unlink($path);
        }
    }
}
